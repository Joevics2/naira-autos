// lib/vehicle/engineNumberPatterns.ts
//
// Static database of engine FAMILY codes (not full serial numbers — the
// unique serial that follows a family code cannot be decoded publicly).
// Each entry here should be ONE real, canonical code. Marketing/family
// umbrella names (e.g. "Duratec 2.0", "Smartstream G1.6") and multi-code
// shorthand (e.g. "CA18DE/CA18DET") should be split into individual
// canonical records with the shared name captured via `family` and
// `aliases` instead — that keeps the matcher precise and keeps each
// result page pointing at one real, verifiable code.

export type EngineCodeRecord = {
  /** Canonical code (the one people usually search / stamp) */
  code: string;
  /** Brand / manufacturer */
  brand: string;
  /** Optional parent family for grouping (e.g. "JZ", "K-series", "LS", "EA888") */
  family?: string;
  /** Alternative names / marketing names / common variants */
  aliases?: string[];
  /** Displacement + configuration */
  displacement: string;
  config: string; // e.g. "I4", "V6", "I6 Twin-Turbo", "Flat-4 Turbo"
  /** Short useful notes */
  notes?: string;
  /** 2–6 common applications */
  applications: string[];
  /** Optional rough power range for extra value */
  powerRange?: string;
  /** Confidence weight for matcher (higher = more distinctive) */
  weight?: number;
};

